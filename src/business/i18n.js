const IDX = { ht: 0, fr: 1, en: 2 };

export function makeT(lang) {
  const i = IDX[lang] ?? 0;
  return (key, vars) => {
    let s = D[key]?.[i] ?? D[key]?.[0] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function loc(l, lang) {
  if (!l) return '';
  return l[lang] ?? l.ht;
}
